# 리허설용: 이 세션에서 물려받은 Claude Code 변수를 지우고 실행한다. 사용: source clean-env.sh; cc <claude 인자...>
cc() {
  env -u CLAUDECODE -u CLAUDE_CODE_CHILD_SESSION -u CLAUDE_CODE_SESSION_ID -u CLAUDE_CODE_MESSAGING_SOCKET \
      -u CLAUDE_CODE_MESSAGING_TOKEN -u CLAUDE_PID -u CLAUDE_CODE_SESSION_ATTENDED -u CLAUDE_CODE_ENTRYPOINT \
      -u CLAUDE_CODE_EXECPATH -u CLAUDE_EFFORT -u CLAUDE_CODE_EFFORT_LEVEL \
      CLAUDE_CODE_DISABLE_AUTO_MEMORY=1 claude "$@"
}
